"""可调参数集中在这里，单位为输入数据的单位（题目数据为 mm）。"""

# ---------------------------------------------------------------------------
# 容差
# ---------------------------------------------------------------------------
# 判定"贴墙 / 贴物"的距离容差：矩形边与墙的距离小于该值即视为贴上
CONTACT_TOL = 1.0
# 判定"重叠"的最小穿透深度：穿透小于该值视为仅接触，允许（货架紧贴货架是合法的）
OVERLAP_TOL = 1.0
# 判定"矩形在多边形内"时允许的越界量（贴墙摆放会有亚毫米级误差）
INSIDE_TOL = 1.0
# 冰箱开门侧禁放带很薄（1mm），判重叠时不能用 OVERLAP_TOL，否则会被容差吃掉
STRIP_TOL = 0.01
# 判定一条边能否当作"可贴的直墙"的倾斜容差（相对长度的比例）
WALL_TILT_RATIO = 1e-3

# ---------------------------------------------------------------------------
# 约束强度（题目没写死的工程假设，可按需改）
# ---------------------------------------------------------------------------
# 门洞前方额外禁放深度。0 = 严格按题目字面"不遮挡门洞本身"；
# 若想留出人通行的缓冲区，可改成 800 等数值
DOOR_CLEARANCE_DEPTH = 0.0
# 冰箱开门侧禁放缓冲。题目只说"开门边不能放任何东西"，取极小值 = 不允许任何物品相贴
FRIDGE_OPEN_BUFFER = 1.0

# ---------------------------------------------------------------------------
# 搜索
# ---------------------------------------------------------------------------
# 沿墙滑动的采样步长（越小越精细，越大越快）
SLIDE_STEP = 150.0
# 单个物品最多评估多少个候选位置（超出则等距抽样）
MAX_CANDIDATES = 400
# DFS 每层最多尝试多少个候选
MAX_BRANCH = 10
# 单个朝向下的最大搜索节点数
NODE_BUDGET = 3000
# 单个朝向下的时间预算（秒）
TIME_BUDGET = 10.0
# 朝向聚类容差（度）
FRAME_CLUSTER_TOL = 1.0
# 朝向"吸附"容差：算出来的朝向离 0/90° 很近时直接吸附到正交，输出角度好看，
# 几何上只会带来亚毫米级偏差
FRAME_SNAP_TOL = 0.05
# 紧凑模式：False = 贴墙优先（题目默认口径）；True = 物品尽量往一起挤，
# 让剩余空地更完整（命令行 --compact 开启，用于和贴墙模式做对比）
COMPACT_MODE = False
# 估算剩余空地时的栅格采样格数（越多越准越慢）
GRID_CELLS = 40000
