"""可调参数集中在这里，单位为输入数据的单位（题目数据为 mm）。

摆放规则（本版核心）
------------------
每件物品必须**贴墙**；贴不下的只能沿墙面方向**左右紧邻**另一件物品；
不允许垂直于墙面往房间里凸出去摆第二层。全部贴墙之后，房间中央自然剩下一整块
空地，那就是通道——所以"人能不能走过去"不需要搜索路径，只要保证物品没有侵占
**中央内核**即可（见 distfield.py）。

内核留不出来、沿墙也排不完时，按 RING_LEVELS 逐级降级：
    wall  → inner → free
即"再贴一圈"优先于"摆到房间中央"，因为前者背后仍有支撑、正面仍朝通道。
"""

# ---------------------------------------------------------------------------
# 容差
# ---------------------------------------------------------------------------
# 判定"贴墙 / 贴物"的距离容差：矩形边与墙的距离小于该值即视为贴上
CONTACT_TOL = 1.0
# 判定"重叠"的最小穿透深度：穿透小于该值视为仅接触，允许（货架紧贴货架是合法的）。
# 必须和自检用的 STRICT_TOL 同一把尺子。早先这里是 1.0，于是摆放放过了 0.2 mm 的
# 穿透（斜朝向时两个各自贴墙的物品在角上互相压进去），自检却判违规——
# 而且这种重叠推不开：推开就撞上另一件紧贴着的物品。
OVERLAP_TOL = 0.01
# 判定"矩形在多边形内"时允许的越界量（贴墙摆放会有亚毫米级误差）
INSIDE_TOL = 1.0
# 冰箱开门禁区是 length × length/2 的**实体区域**，不是一条薄带：任何物品都不得
# 压入，紧贴也不行（门板要扫过去）。所以判重叠时用**负容差**——间隙小于
# CONTACT_TOL 就否掉，和 @fridge_open_strip 里的判据保持一致。
# 用正的 0.01 会留下一段"摆放时放过、自检时判违规"的灰色地带。
STRIP_TOL = -1.0
# 判定一条边能否当作"可贴的直墙"的倾斜容差（相对长度的比例）
WALL_TILT_RATIO = 1e-3

# ---------------------------------------------------------------------------
# 门
# ---------------------------------------------------------------------------
# 门洞前方额外禁放深度。光靠"门两侧墙段不许贴"挡不住从相邻墙面延伸过来堵门的设备，
# 所以门洞正前方还要留一块通行缓冲，人进门才有回旋余地。
# 这块不能贪大：它是**硬禁放区**，和冰箱的开门禁区（length × length/2）叠加后会
# 互相抢地——实测 800 会把 example4 的冰箱逼到 0 个可用位置（400 时还有 1 个）。
# 门能不能真的走进去另有一套独立复核（corridor_report：栅格腐蚀 + 门可达），
# 这里只管"别把东西怼在门脸上"，不必替复核把整条通道都预留出来
DOOR_CLEARANCE_DEPTH = 400.0
# 门洞两侧各留这么长的墙面不许贴东西（疏散净空，人进门要有回旋余地）
DOOR_SIDE_CLEARANCE = 900.0
# 上面那条禁区的厚度。做薄一点——它唯一的作用是"让这段墙不能贴"，
# 太厚会白白吃掉可用面积
DOOR_CLEAR_DEPTH = 120.0
# 冰箱开门禁区。题目说"冰箱 length 的其中一边为开门边，开门边不能放任何东西"——
# 这句话的落点是"门要能真的打开"，不是"贴着门那条边不许放东西"：
# 对开门冰箱每扇门宽 length/2，绕铰链转 90°，门板扫过的就是一块
#     宽 = length（整条开门边） ×  深 = length/2（门扇旋转半径）
# 的矩形。这块是**硬禁放区**：任何物品都不得压入，包括紧贴。
# 冰箱 1220×1330 → 禁区 1220×610。
FRIDGE_OPEN_DEPTH_RATIO = 0.5

# ---------------------------------------------------------------------------
# 人的操作空间（设备贴墙后，人站在通道里操作）
# ---------------------------------------------------------------------------
ACCESS_DEPTH = 600.0
FRIDGE_ACCESS_DEPTH = 900.0
MIN_ACCESS_DEPTH = 400.0
FRIDGE_MIN_ACCESS_DEPTH = 600.0
# 冰箱开门边正前方至少要空出多少（门扇打开 + 人站得下）。
# 比操作深度宽松：贴墙时 front_clear_ok 已经按 FRIDGE_ACCESS_DEPTH 卡过一遍，
# 这条主要管"冰箱被摆到房间中央"时门不能正对墙
FRIDGE_DOOR_CLEAR = 600.0
FRIDGE_DOOR_CLEAR_MIN = 400.0

# ---------------------------------------------------------------------------
# 中央内核（通道）
# ---------------------------------------------------------------------------
# 是否保留中央通道：是则物品一律不得侵占内核
ENABLE_AISLE = True
# 通道保证宽度；房间不够大时会自动按 80% / 下限逐级收窄
AISLE_WIDTH = 800.0
# 收窄下限：再窄人就过不去了
AISLE_MIN_WIDTH = 600.0
# 距离场栅格格数（越大越准越慢；只在建场时算一次）
DIST_FIELD_CELLS = 20000

# ---------------------------------------------------------------------------
# 搜索
# ---------------------------------------------------------------------------
SLIDE_STEP = 150.0
MAX_CANDIDATES = 400
# 每件物品最多换几个候选位置再往下走（还会按深度递减，见 _dfs）。调大能搜得更全，
# 但代价是几何级增长——10 就足以让单个场景跑上百秒
MAX_BRANCH = 6
# **节点预算是搜索深度的主约束**，必须让它说了算：用墙钟时间当主约束的话，
# 同一份输入在不同负载的机器上会搜出不同的解，结果不可复现。
# TIME_BUDGET 只是病态输入下的兜底闸，正常情况不应该碰到。
NODE_BUDGET = 1000
TIME_BUDGET = 120.0
FRAME_CLUSTER_TOL = 1.0
FRAME_SNAP_TOL = 0.05

# ---------------------------------------------------------------------------
# 降级顺序（物品沿墙排不下时怎么办）
# ---------------------------------------------------------------------------
# wall  : 只允许贴墙、或沿墙面方向左右紧邻另一件物品（标准做法）
# inner : 允许贴在已放物品朝内那一面，即沿墙方向再长一排（仍不得侵占内核）
# free  : 内核也不要了，剩下的物品摆到房间中央
RING_LEVELS = ("wall", "inner", "free")

# 估算剩余空地时的栅格采样格数（只用于出指标，不参与决策）
GRID_CELLS = 16000
